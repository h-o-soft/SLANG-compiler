	LD	E, (HL)
	INC	HL
	LD	D, (HL)
	INC	HL
	PUSH	DE
	DJNZ	.LOOP2
	; A = 残り引数 をBに入れておく(ループ回数)
	LD	B, A
	; 描画色
	LD	A, (HL)
	LD	(PAINTCOL), A
