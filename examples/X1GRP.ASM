; INPUT:
;	BC = VRAMアドレス
;	A  = 塗りマスク
MASKDRAW:
	LD	D,A			; 塗りマスクを保存しておき
	IN	E,(C)			; そこのビット情報を拾い
MASKCOL2:
	OR	0AAh			; タイル1を設定
MASKTILE1:
	; 塗る場合
	CPL
	OR	E
;	; 塗らない場合こっちになる
;	NOP
;	AND	E
	LD	E,A			; とりあえず保存し
	LD	A,D			; 塗りマスクを戻し
MASKCOL1:
	OR	055h			; タイル2を設定
MASKTILE2:
	; 塗る場合
	CPL
	OR	E
;	; 塗らない場合こっちになる
;	NOP
;	AND	E
	OUT	(C),A
	RET
