PAINTPARAMS:
	DS	12
; INPUT:
;	HL = VRAM base address
;	B  = target pixel
; OUTPUT:
;	A  = Color(0〜7)
;
; TRASHED:
;	none
GETPIXEL:
	PUSH	BC
	PUSH	DE
	LD	D,B	; target pixel
	LD	E,0	; color
	LD	B,H
	LD	C,L
	SET	6,B	; 4000h
	IN	A,(C)	; BLUE
	AND	D
	JR	Z,.NOBLUE
	LD	E,1
.NOBLUE
	SET	7,B	; C000H
	IN	A,(C)	; GREEN
	AND	D
	JR	Z,.NOGREEN
	SET	2,E
.NOGREEN
	RES	6,B
	IN	A,(C)	; RED
	AND	D
	JR	Z,.NORED
	SET	1,E
.NORED
	LD	A,E
	POP	DE
	POP	BC
	RET
PATCH_TBL:
	DW	RIGHTWIDTH
	CP	40
	CP	80
	DW	CALCVRWIDTH+1
	DW	-320
	DW	-640
	DW	W80DOUBLE
	NOP
	LD	B,H
	ADD	HL,HL
	LD	B,H
	DW	VRUPWIDTH
	SUB	40
	SUB	80
	DW	VRDNWIDTH
	ADD	A,40
	ADD	A,80
	DW	VRDNCMP
	CP	3
	CP	7
	DW	VRDNCMP2
	CP	0E8h
	CP	0D0h
	DW	SETLPCOUNT
	LD	A,2Bh
	LD	A,16h
	DW	LDBUFSZ+1
	DW	03E8h
	DW	07D0h
PAINTMAIN:
	; キュー初期化
	LD	A, 0FFh
	LD	(BUF_HEAD),A
	LD	(BUF_TAIL),A
	; DE,HLでVRAMアドレスを算出(HL、B、裏Aが返る)
	CALL	CALCVRAMADR
; まず、塗り開始位置が境界色かどうか調べる
PAINTLOOP:
	CALL	CHECKCOL
	LD	D,A
	AND	B
	JP	NZ,DEQUEUE
	LD	A,D
; 非境界色の場合は左側境界を探す
SEARCHLEFT:
	OR	A
	JR	Z,LEFT8		; 境界色がないので左に移動
; 境界色を見つけたのでBを左に動かして実際の位置を探す
SEARCHLEFT2:
	LD	D,A
	AND	B
	JR	NZ,FLEFTBORDER
	LD	A,D
	RLC	B
	JR	NC,SEARCHLEFT2
	; 左端までチェックしたら8ドット境界で左に移動
LEFT8:
	; チェックビットを左端に移動させる
	LD	B,80h
	; 左端か？
	EX	AF,AF'
	DEC	A
	; 左端の場合はVRAM位置が左端でビット位置左端(80h)が塗り開始位置となる
	JP	M,LEFTEND
	EX	AF,AF'
	; VRAM8ドット左に移動
	DEC	HL
	; 境界色を得る
	CALL	CHECKCOL
	RLC	B	; 80h→01h
	JR	SEARCHLEFT
; 左端に到達したのでここを境界とする
; 左のボーダーを発見した
FLEFTBORDER:
	; 実際には境界上にサーチ位置があるので
	; ボーダーを右に移動させる
	RRC	B
	JR	NC,LEFTEND
	; 8ドット境界をまたいだので境界を右に移動
	INC	HL
	EX	AF,AF'
	INC	A
	EX	AF,AF'
LEFTEND:
	; 塗り開始位置を保存する
	CALL	SETUPPAINT
	; この位置を開始位置として今度は右側を探す
	CALL	CHECKCOL
	; 開始位置の境界ビットを保存
	LD	D,A
	; Bは大丈夫な位置のはずなのでそのすぐ右から見ていく
SEARCHRIGHT:
	RRC	B
SEARCHRIGHT2:
	JR	C,RIGHT8
	AND	B
	JR	NZ,FRIGHTBORDER	; 右端の境界ドットを発見
	LD	A,D
	JR	SEARCHRIGHT
; 8ドットをまたいだので右に移動
RIGHT8:
	INC	HL
	EX	AF,AF'
	INC	A
	; TODO 自己書き換えでWIDTH数にする
RIGHTWIDTH:
	CP	40
	JR	Z,RIGHTEND0
	EX	AF,AF'
	CALL	CHECKCOL
	; 境界ビットが無い場合はそのまま右に移動
	OR	A
	JR	Z,RIGHT8
	LD	D,A
	JR	SEARCHRIGHT2
RIGHTEND0:
	EX	AF,AF'
FRIGHTBORDER:
; 境界上にあるので左に移動させる
	RLC	B
	JR	NC,RIGHTEND
	DEC	HL
	EX	AF,AF'
	DEC	A
	EX	AF,AF'
RIGHTEND:
	; 右端の情報諸々を保存する
	LD	A,B
	LD	(RIGHTBIT),A	; 右端ビット
	LD	A,(XPOSDIV8)
	LD	B,A
	EX	AF,AF'
	SUB	B
	LD	(PAINTREMAIN),A	; 塗るX/8の数
	LD	HL,(VRAMADDR)	; 左端のVRAMアドレスを得てHLに入れなおし
	CALL	VRAMUP		; 上に移動させ
	CALL	NC,CHKENQUEUE	; キャリーが立っていなかったら上の行をチェックしてキューに入れる
	LD	HL,(VRAMADDR)	; ふたたび左端のVRAMアドレスを得てHLに入れなおし
	CALL	VRAMDOWN	; VRAMアドレスを一行ぶん下に移動させ
	CALL	NC,CHKENQUEUE	; キャリーが立っていなかったら下の行をチェックしてキューに入れる
	LD	A,(RIGHTBIT)	; 右端の位置情報をAに得ておく
	EX	AF,AF'
	; 1ライン塗る処理
	CALL	DRAWLINE
DEQUEUE:
	; キューが尽きたかチェック
	LD	A, (BUF_TAIL)
	LD	D,A
	LD	A,(BUF_HEAD)
	CP	D
	RET	Z			; キューに何も入っていないので終了
	; なんか入ってるのでキュー先頭から拾う
	INC	A
	LD	(BUF_HEAD),A
	JR	NZ,.NOHEAD		; HEADが0以外なら普通にBUF_HEADから拾い、0なら初期化して先頭に戻す
	LD	HL,(BUFADR)		; BACKUP_ADR
	JR	.DEQUEUESTART
.NOHEAD
	LD	HL,(BUFADR_HEAD)
.DEQUEUESTART
	LD	E,(HL)			; VRAMアドレスを取得
	INC	HL
	LD	D,(HL)
	INC	HL
	LD	B,(HL)			; 塗り対象ビット
	INC	HL
	LD	A,(HL)			; X/8とEVENODDを混ぜたもの
	INC	HL
	LD	C,A
	AND	080h			; EVENODDのみ取り出す
	LD	(EVENODD),A
	CPL				; 80h or 00hなので、7fh or ffhになる
	AND	C			; X/8成分のみをAに取り出す
	EX	AF,AF'			; ↑のAを裏Aに入れてやる
	LD	(BUFADR_HEAD),HL	; リングバッファを更新し
	EX	DE,HL			; 取り出したVRAMアドレスをHLに入れて
	JP	PAINTLOOP		; 塗りをループさせる
PAINTEND:
	RET
CHKENQUEUE:
	; この位置から右側にPAINTREMAINぶんだけ走査してキューに入れてやる
	; まずは開始位置と終了位置が同じかどうか見るが
	; その前に下記対応をする
	; 裏(現在)のAを X/8 にする
	; 裏のdを塗り残りバイト数にする(remain)
	; 裏のeも何かに使うはず
	; 表のBを塗り対象ビットにする
	LD	A,(XPOSDIV8)	; 裏AをX/8に
	EX	AF,AF'
	LD	A,(PAINTBIT)
	LD	B,A		; 表Bを塗り開始ビットに
	EXX
	LD	A,(RIGHTBIT)	; 裏Eを終端ビットに
	LD	E,A
	LD	A,(PAINTREMAIN)	; 裏Dを塗り残りバイト数に
	LD	D,A
	EXX
	OR	A
	JR	Z,CHKRIGHT	; 塗り開始ビットと塗り終了ビットが同じなので1バイト以上またいで探す必要なし
	BIT	7,B			; 塗り対象ビットが左端か調べて
	JR	NZ,CHKLEFTLOOP		; 左端の場合は全ビットが境界色の場合があるのでそのチェックをする
	CALL	CHECKCOL		; 左端じゃないの場合は現在のHLのVRAM位置の境界色をAに得て
	JR	CCHKLOOP1		; ここに飛ぶ(通常チェック)
CHKLEFTLOOP:
	CALL	CHECKCOL		; まずは現在位置の境界色状況を確認し
	CP	0FFh			; 全てが境界色だった場合は
	JR	Z,BORDERLEFT		; いちいちチェックする必要がないのでここでX/8単位の右に移動させる処理に飛ぶ
;====================================================================
; 非境界色を発見したらキューに入れる
;====================================================================
CCHKLOOP1:
	LD	C,A
CCHKLOOP:
	AND	B
	JR	Z,FOUNDPOINT		; 非境界色なのでキューに溜める
CBORDER:
;-----------------------------
;現在境界色なので右に移動させる
;-----------------------------
	RRC	B
	LD	A,C
	; バイトまたいだか？
	JR	NC,CCHKLOOP	; またいでなければチェック継続
BORDERLEFT:
	; またいだので右に移動
	EX	AF,AF'
	INC	A		; X/8位置を右に
	EX	AF,AF'
	INC	HL
	EXX
	DEC	D		; 残りバイト数を減らす
	EXX
	JR	Z,CHKRIGHT	; 残りバイト数が尽きたら右側チェック?
	JR	CHKLEFTLOOP	; 尽きてないので境界色が続いているという事なのでループする
;====================================================================
; 非境界色の先頭なのでまずはキューにためる
; 非境界色が尽きるまで右に移動し、
; 境界色を発見したら境界色の中で非境界色を探す処理に遷移する
;====================================================================
FOUNDPOINT:
	CALL	ENQUEUE		; まずは非境界色を塗り対象としてキューに蓄積
NBLOOP:
	LD	A,C		; 境界ビットをAに入れる
	RRC	B		; チェックする位置を右に1ドットずらす
	JR	NC,SBORDER2	; チェックビットが右端をハミ出てなければ境界色探しループを継続
	; ハミだしてたらVRAM位置を右に
	INC	HL
	EX	AF,AF'
	INC	A		; X/8位置を右に
	EX	AF,AF'
	EXX
	DEC	D
	EXX
	JR	Z,CHKRIGHT	; 残りバイト数が尽きたので右チェック
	; 尽きてないので現在の情報を取得し
	CALL	CHECKCOL
	LD	C,A
SBORDER2:
	AND	B		; チェックする
	JR	NZ,CBORDER	; 境界色の中で非境界色を探すところに戻る
	; まだ非境界色なので境界色探しを続ける
	JR	NBLOOP
; 右端終端までチェックを進める
CHKRIGHT:
	CALL	CHECKCOL		; 現在のVRAM位置の境界色を得て
	LD	C,A			; それをCに保存しておく
CHKRIGHTLOOP:
	AND	B			; チェックして
	JR	Z,FOUNDBORDER2		; 非境界色ならここに飛び
CHKRIGHTLOOP2:
	EXX
	LD	A,E			; 右端の塗り終端ビットをAに入れ
	EXX
	CP	B			; 終端までいったかをチェックして
	RET	Z			; 終端までいったらキューに入れる処理終了
	RRC	B			; いってなかったらチェックビットを右にズラして
	LD	A,C			; VRAM境界情報をAに入れて
	JR	CHKRIGHTLOOP		; 再度チェック
FOUNDBORDER2:
	CALL	ENQUEUE			; 非境界色をキューに入れる
	JR	FOUNDENDCHK
CHKRIGHT2:
	CALL	CHECKCOL
	LD	C,A
NBRIGHTLOOP:
	AND	B			; チェック位置とANDをとって
	JR	NZ,CHKRIGHTLOOP2	; 境界色だったら右端チェックに戻る
FOUNDENDCHK:
	EXX
	LD	A,E			; 右端終端チェック
	EXX
	CP	B			; 終端に到達したかを調べ
	RET	Z			; 到達していたら終了
	LD	A,C			; 到達していない場合は境界情報をAに戻し
	RRC	B			; チェック位置を右に1つずらして
	JR	NBRIGHTLOOP		; 境界色チェックに戻る
DRAWLINE:
	; Cは塗り色変数
	LD	A,(PAINTCOL)
	LD	C,A
	; BはVRAM3プレーンぶんのループ
	LD	B,3
	; DはVRAMアドレスに足しこむ値
	LD	D,0
DRAWLOOP:
	RRC	C			; 塗り色を右ローテートさせて
	JR	C,.DRAWCOL		; 該当色が有効ならここに飛び
	LD	HL, 0A300h		; 有効じゃない場合はHLに0A300hを入れ
	ld	E, 0			; Eに0を入れ
	JR	NODRAWCOL		; ここに飛ぶ
.DRAWCOL
	LD	HL,0B32Fh		; 該当色が有効の場合はb32fhをhlに入れて
SETCOL1:
	LD	E,055H			; eにタイル状態を入れ(ここは事前に書き換える事)
NODRAWCOL:
	LD	A,0
	LD	(MASKTILE1),HL		; タイル一色目を塗るかどうか
	BIT	3,C			; タイル二色目が塗りかどうか
	JR	NZ,.DRAWCOL2
	LD	HL, 0A300h		; 有効じゃない場合はHLに0A300hを入れ
	XOR	A
	JR	NODRAWCOL2
.DRAWCOL2
	LD	HL,0B32fh
SETCOL2:
	LD	A,0AAh			; TODO 塗りパターン2を入れる
NODRAWCOL2:
	LD	(MASKTILE2),HL		; タイル2色目を塗るかどうか
	; タイル2色ぶん情報を混ぜてAに入れてやる
	OR	E
	; まとめ塗りの色を入れておく
	LD	(BLOCKDRAW+1),A
	; VRAMアドレス加算(4000h→8000h→C000h)
	LD	A,D
	ADD	A,040H
	LD	D,A
	EXX
	LD	BC,(VRAMADDR)
	OR	B
	LD	B,A
	; BCが描画VRAMアドレスになっているはず
	LD	A,(PAINTREMAIN)		; 塗りチェック残り/8を
	LD	L,A			; Lに入れて
	LD	A,(PAINTBIT)		; 塗り対象ビットを
	LD	D,A			; Dに入れて
	XOR	A			; Aを0にして
	JP	.LEFTMASK		; 左側マスク部分を塗る
.LEFTMASKLOOP
	OR	D			; 塗り開始対象ビットとORして
.LEFTMASK
	RLC	D			; 塗り開始対象ビットを左ローテートさせて
	JP	NC,.LEFTMASKLOOP	; 左がハミでるまでループ
	DEC	L			; 塗りチェック残り/8を1減らして
	INC	L			; 戻して
	JR	Z, PAINTRIGHT		; 塗りチェック残り/8が0だったらここに飛ぶ(つまりブロック単位で塗る必要がなければ右側描画処理に飛ぶ)
	CALL	MASKDRAW		; 左または右側の実描画処理
	INC	BC
	; PAINTREMAINが尽きるまでマスクカラーで塗ってやる
BLOCKDRAW:
	LD	A,0FFh			; ここの0は実際の塗りのパターンで書き換えられている
	JP	BLOCKPAINT1
BLOCKPAINT:
	OUT	(C),A			; Aで塗る
	INC	BC
BLOCKPAINT1:
	DEC	L			; 塗り残し数
	JP	NZ,BLOCKPAINT		; 8ドットぶん、モリモリ塗っていく
	JR	BLOCKEND
	; 右側を塗る(混ぜる)
PAINTRIGHT:
	EX	AF,AF'
	LD	D,A			; 右端ビット情報をdに入れて
	EX	AF,AF'
	JR	RIGHTMASK
BLOCKEND:
	LD	A,(RIGHTBIT)		; 右側終端ビット
	LD	D,A
	XOR	A
	JP	RIGHTMASK
RIGHTMASKLOOP:
	OR	D
RIGHTMASK:
	RRC	D
	JP	NC,RIGHTMASKLOOP
	CALL	MASKDRAW		; 右側の実描画処理
	EXX
	DJNZ	DRAWLOOP
	RET
