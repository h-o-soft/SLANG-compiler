ENQUEUE:
	; キューを進める
	LD	A,(BUF_HEAD)
	LD	D,A
	LD	A,(BUF_TAIL)
	INC	A
	CP	D
	; TAILがHEADに追い付いてしまったらバッファが尽きたという事
	JP	Z,PAINTERR
	; バッファ尽きてないのでキューに足せる
	LD	(BUF_TAIL),A
	; 初期状態 or ひとまわりした？
	OR	A
	EX	DE,HL			; VRAMアドレスをDEに移す
	JR	NZ,.NOBUFINIT
	LD	HL,(BUFADR)		; BACKUP_ADR	; TODO バッファ先頭アドレスは動かせるようにする
	JR	.STARTENQUEUE
.NOBUFINIT
	LD	HL,(BUFADR_TAIL)
.STARTENQUEUE
	LD	(HL),E			; VRAMアドレスをキューに入れる
	INC	HL
	LD	(HL),D
	INC	HL
	LD	(HL),B			; 現在位置ビットを保存
	INC	HL
	LD	A,B			; Bを使うので表Aにバックアップしておく
	EX	AF,AF'
	LD	B,A			; X/8の値
	LD	A,(EVENODD)		; 偶数奇数フラグ
	OR	B			; を、混ぜて保存
	LD	(HL),A
	INC	HL
	LD	A,B			; X/8の値を戻す
	EX	AF,AF'
	LD	B,A			; 表Aにバックアップしておいたチェック対象ビットを戻す
	LD	(BUFADR_TAIL),HL
	EX	DE,HL			; DEに入っているVRAMアドレスをHLに戻す
	RET
