; libsos_base.asm — 機種非依存 S-OS 共通ランタイム
; SLANG Runtime Library (new format)
;
; S-OS 標準 BIOS API のみを利用し、特定機種のハードウェアには依存しない。
; X1 固有の CTC 検出・X1turbo 割り込みパッチが必要な場合は libsosx1_base を使用。

; @name SLANGINIT
; @calls RRET,SOSCALLS
EXX
POP HL
LD (RETADR-2), HL
EXX
PUSH BC
PUSH DE
PUSH HL
PUSH IX
PUSH IY
LD (RSP-2),SP

LD A,(sWIDTH)
LD (AT_WIDTH),A

; WORK ZERO CLEAR
XOR A
LD HL,__WORK__
LD DE,__WORK__+1
LD BC,__WORKEND__-__WORK__-1
LD (HL),A
LDIR

; SP=$0000
DB 0,0,0

<<CALLINITIALIZER>>

LD IY,__IYWORK

CALL MAIN
OR A

RRET:
LD SP,0
RSP:
POP IY
POP IX
POP HL
POP DE
POP BC
JP $0000
RETADR:


; @name STOP
; @param_count 0
SCF
JP RRET


; @name SOSCALLS
; @works AT_WIDTH:1,_WK1FD0:1
sLPTOF  EQU 1FD6H
sLPTON  EQU 1FD9H
sLPRNT  EQU 1FDCH
sPRINT  EQU 1FF4H
sWIDCH  EQU 2030H
sSCRN   EQU 201BH
sLOC    EQU 201EH
sGETKY  EQU 1FD0H
sFLGET  EQU 2021H
sINKEY  EQU 1FCAH
sCSR    EQU 2018H
sGETL   EQU 1FD3H
sHLHEX  EQU 1FB2H
sKBFAD  EQU 1F76H

sMEMAX  EQU 1F6AH
sFILE   EQU 1FA3H
sDSK    EQU 1F5DH
sFATPOS EQU 1F5EH
sDIRPS  EQU 1F60H
sDTBUF  EQU 1F64H
sIBFAD  EQU 1F74H
sDRDSB  EQU 2000H
sDWTSB  EQU 2003H

sTPCHK  EQU 2863H

sWIDTH  EQU 1F5CH


; @name BEEP
CALL $1FC4
RET


