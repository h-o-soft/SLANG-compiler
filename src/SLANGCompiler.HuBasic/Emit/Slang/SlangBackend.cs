using System.Text;
using SLANGCompiler.HuBasic.Analysis;
using SLANGCompiler.HuBasic.Lowering;
using SLANGCompiler.HuBasic.Parsing;

namespace SLANGCompiler.HuBasic.Emit.Slang;

/// <summary>
/// SLANG のソースを出す後段。
/// 名前: 整数変数 V_名前 (% は _I)、文字列変数 S_名前、整数配列 A_名前、隠し変数 H_…、
/// 文字列リテラル K_番号、行ラベル L行番号。浮動小数の定数の表 H_FK[]、浮動小数の一時変数 H_F番号。
/// 全体を MAIN() 1 関数にし、すべての二項演算を括弧で囲んで優先順位を固定する。
/// 浮動小数: SLANG は小数部のない FLOAT の定数どうしを整数として畳み込むので、定数はすべて表 H_FK[] から読む。
/// 割り算・比較・整数からの変換は、値を一時変数に入れてから (その文の行の前に代入を出して) 番地で渡す。
/// </summary>
public sealed class SlangBackend : IHuBackend
{
    private readonly StringBuilder _sb = new();   // MAIN の本体
    private HuProgram _prog = null!;
    private readonly List<string> _pre = new();   // いまの文の行の前に出す代入 (浮動小数の一時変数)
    private readonly List<double> _fconsts = new();
    private readonly Dictionary<long, int> _fconstIds = new();
    private int _ftemp;      // いまの文で使った浮動小数の一時変数の数
    private int _maxFtemp;   // 文ごとの最大 (宣言する数)

    public string Emit(HuProgram program, HuFlat flat, HuEmitOptions options)
    {
        _prog = program;
        _sb.Clear();
        _pre.Clear();
        _fconsts.Clear();
        _fconstIds.Clear();
        _maxFtemp = 0;
        // 本体を先に作る (浮動小数の定数と一時変数の数は、本体を作り終えるまで分からない)
        foreach (var op in flat.Ops) EmitOp(op, options);

        var head = new StringBuilder();
        head.AppendLine("// generated by hub2sl - do not edit");
        if (options.SourceName.Length > 0) head.AppendLine($"// source: {options.SourceName}");
        head.AppendLine();
        EmitDeclarations(head, flat);
        head.AppendLine();
        head.AppendLine("MAIN()");
        head.AppendLine("BEGIN");
        head.Append(_sb);
        head.AppendLine("END;");
        return head.ToString();
    }

    // ------------------------------------------------------------ 名前

    public static string IntVarName(string name) => "V_" + Bare(name);
    public static string StrVarName(string name) => "S_" + Bare(name);
    public static string ArrayName(string name) => "A_" + Bare(name);
    public static string LiteralName(int id) => "K_" + id;

    private static string Bare(string name)
    {
        if (name.EndsWith('%')) return name[..^1] + "_I";
        if (name.EndsWith('$')) return name[..^1];
        return name;
    }

    public static string HiddenName(string hidden)
    {
        if (hidden == HuLowerer.Temp) return "H_T";
        if (hidden == HuLowerer.CurrentLine) return "H_LINE";
        if (hidden.StartsWith("DIM:")) return "H_DIM_" + Bare(hidden[4..]);
        if (hidden.StartsWith("UB:")) return "H_UB_" + Bare(hidden[3..]);
        return "H_" + hidden;
    }

    // ------------------------------------------------------------ 宣言

    private void EmitDeclarations(StringBuilder _sb, HuFlat flat)
    {
        var vars = _prog.IntVars.Select(IntVarName).Concat(flat.HiddenVars.Select(HiddenName)).ToList();
        foreach (var chunk in vars.Chunk(8))
            _sb.AppendLine($"VAR {string.Join(", ", chunk)};");
        // 浮動小数の一時変数 (SLANG は変数ごとに型を書かないと WORD になる)
        var ftemps = Enumerable.Range(1, _maxFtemp).Select(i => "FLOAT " + FTempName(i)).ToList();
        foreach (var chunk in ftemps.Chunk(8))
            _sb.AppendLine($"VAR {string.Join(", ", chunk)};");
        if (_fconsts.Count > 0)
            _sb.AppendLine($"ARRAY FLOAT H_FK[] = {{ {string.Join(", ", _fconsts.Select(FloatLiteral))} }};");
        foreach (var (name, bound) in _prog.Arrays)
            _sb.AppendLine($"ARRAY {ArrayName(name)}[{bound}];");
        foreach (var s in _prog.StrVars)
            _sb.AppendLine($"ARRAY BYTE {StrVarName(s)}[255];");
        for (int i = 0; i < _prog.Literals.Count; i++)
        {
            var text = _prog.Literals[i];
            var bytes = new List<int> { text.Length };
            bytes.AddRange(text.Select(c => (int)c));
            _sb.AppendLine($"ARRAY BYTE {LiteralName(i)}[] = {{ {string.Join(",", bytes)} }};");
        }
        if (_prog.DataBytes.Length > 0)
        {
            _sb.AppendLine("ARRAY BYTE H_DATA[] = {");
            foreach (var chunk in _prog.DataBytes.Chunk(24))
                _sb.AppendLine("  " + string.Join(",", chunk.Select(b => b.ToString())) + ",");
            _sb.AppendLine("  0 };");
            var dl = new List<int>();
            foreach (var (line, offset) in _prog.DataLines)
            {
                dl.Add(line);
                dl.Add(offset);
            }
            dl.Add(0xFFFF);
            dl.Add(_prog.DataBytes.Length);
            // 初期値の並び (CODE リスト) の要素は既定で 1 バイト。2 バイトの要素は % を付ける
            _sb.AppendLine($"ARRAY H_DLINE[] = {{ {string.Join(",", dl.Select(v => "%" + Hex(v)))} }};");
        }
    }

    private static string Hex(int v) => v > 32767 || v < 0 ? $"${v & 0xFFFF:X4}" : v.ToString();

    // ------------------------------------------------------------ 文

    /// <summary>文の行を出す。その前に、式を作るときに溜まった一時変数への代入を出す</summary>
    private void Line(string s)
    {
        foreach (var p in _pre) _sb.Append("  ").AppendLine(p);
        _pre.Clear();
        _sb.Append("  ").AppendLine(s);
    }

    private void EmitOp(FlatOp op, HuEmitOptions options)
    {
        _ftemp = 0;
        switch (op)
        {
            case FLabel l:
                _sb.AppendLine($"{l.Name}:");
                break;
            case FLineMark m:
                if (options.LineComments) _sb.AppendLine($"  // BAS {m.Line}: {CommentSafe(m.Source)}");
                break;
            case FGoto g:
                Line($"GOTO {g.Label};");
                break;
            case FIf f:
                Line($"IF {Cond(f.Cond)}{(f.JumpIfTrue ? "" : "==0")} THEN GOTO {f.Label};");
                break;
            case FIfHidden fh:
            {
                var opText = fh.Op switch { "==" => "==", "<" => ".<.", ">" => ".>.", ">=" => ".>=.", _ => fh.Op };
                Line($"IF {HiddenName(fh.Hidden)} {opText} {Num(fh.Value)} THEN GOTO {fh.Label};");
                break;
            }
            case FAssign a:
                Line($"{LValue(a.Target)}={Int(a.Value)};");
                break;
            case FAssignHidden ah:
                Line($"{HiddenName(ah.Hidden)}={Int(ah.Value)};");
                break;
            case FCall c:
            {
                var call = $"{c.Function}({string.Join(", ", c.Args.Select(Arg))})";
                Line(c.Result != null ? $"{HiddenName(c.Result)}={call};" : $"{call};");
                break;
            }
            case FDispatch d:
            {
                var cases = string.Join(" ", d.Cases.Select(cs => $"{Num(cs.Value)}: GOTO {cs.Label};"));
                Line($"CASE {HiddenName(d.Hidden)} OF {{ {cases} }};");
                break;
            }
            case FPortOut po:
                Line($"PORT[{Int(po.Port)}]={Int(po.Value)};");
                break;
        }
    }

    private static string CommentSafe(string s)
    {
        var sb = new StringBuilder();
        foreach (var c in s) sb.Append(c >= 0x20 && c < 0x7F ? c : '?');
        return sb.ToString();
    }

    private string Arg(FArg a) => a switch
    {
        FExprArg e => e.Expr.Type == HuType.Str ? Str(e.Expr) : Int(e.Expr),
        FFloatArg f => Flt(f.Expr),
        FIntArg i => Num(i.Value),
        FAddrArg av => "&" + LValueName(av.Var),
        FHiddenAddrArg h => "&" + HiddenName(h.Hidden),
        FDataTableArg t => t.LineTable ? "H_DLINE" : "H_DATA",
        _ => throw new InvalidOperationException(a.ToString()),
    };

    private static string Num(int v) => v < 0 ? $"(0-{-v})" : Hex(v);

    private static string LValueName(HuExpr e) => e switch
    {
        HuVar v => IntVarName(v.Name),
        _ => throw new InvalidOperationException("address of " + e),
    };

    private string LValue(HuExpr e) => e switch
    {
        HuVar v => v.Type == HuType.Str ? StrVarName(v.Name) : IntVarName(v.Name),
        HuIndex ix => ArrayElement(ix),
        _ => throw new InvalidOperationException(e.ToString()),
    };

    private string ArrayElement(HuIndex ix)
        => $"{ArrayName(ix.Name)}[BAS_AIDX({Int(ix.Index)}, &{HiddenName(HuLowerer.DimState(ix.Name))}, &{HiddenName(HuLowerer.UpperBound(ix.Name))})]";

    // ------------------------------------------------------------ 式

    private static readonly Dictionary<string, string> SignedCompare = new()
    {
        ["="] = "==", ["<>"] = "<>", ["<"] = ".<.", [">"] = ".>.", ["<="] = ".<=.", [">="] = ".>=.",
    };

    /// <summary>条件の位置の式。最上位が比較なら 1/0 のまま、それ以外は値そのもの (0 以外が真)。</summary>
    private string Cond(HuExpr e)
    {
        if (e is HuBinary b && SignedCompare.ContainsKey(b.Op))
            return Compare(b);
        // 浮動小数の条件は、四捨五入で整数にしてから 0 でないかを見る (Hu-BASIC の実測: IF .25 は偽、IF .5 は真)
        return $"({Int(e)})";
    }

    /// <summary>比較を SLANG の 1/0 の式にする</summary>
    private string Compare(HuBinary b)
    {
        if (b.Left.Type == HuType.Float || b.Right.Type == HuType.Float)
        {
            // 浮動小数の比較は BAS_FCMP (厳密に比べて -1/0/1) と 0 の比較にする
            var cmp = $"BAS_FCMP({FAddr(b.Left)}, {FAddr(b.Right)})";
            return $"({cmp} {SignedCompare[b.Op]} 0)";
        }
        if (b.Left.Type == HuType.Str)
        {
            var cmp = $"BAS_SCMP({Str(b.Left)}, {Str(b.Right)})";
            return b.Op switch
            {
                "=" => $"({cmp}==0)",
                "<>" => $"({cmp}<>0)",
                _ => $"({cmp} {SignedCompare[b.Op]} 0)",
            };
        }
        return $"(({Int(b.Left)}) {SignedCompare[b.Op]} ({Int(b.Right)}))";
    }

    /// <summary>整数の式 (値。比較は -1/0 に変換する)</summary>
    private string Int(HuExpr e)
    {
        if (e.Type == HuType.Float) return IntFromFloat(e);
        switch (e)
        {
            case HuNum n:
                return Num(n.Value);
            case HuVar v:
                return IntVarName(v.Name);
            case HuIndex ix:
                return ArrayElement(ix);
            case HuUnary u:
                return u.Op switch
                {
                    "-" => $"(0-({Int(u.Operand)}))",
                    "+" => Int(u.Operand),
                    _ => $"(CPL ({Int(u.Operand)}))", // NOT はビット反転
                };
            case HuBinary b:
                if (SignedCompare.ContainsKey(b.Op))
                    return $"(0-{Compare(b)})";
                return b.Op switch
                {
                    "+" => $"(({Int(b.Left)})+({Int(b.Right)}))",
                    "-" => $"(({Int(b.Left)})-({Int(b.Right)}))",
                    "*" => $"(({Int(b.Left)})*({Int(b.Right)}))",
                    "/" => $"BAS_IDIVR({Int(b.Left)}, {Int(b.Right)})",
                    "\\" => IsNonZeroConst(b.Right)
                        ? $"(({Int(b.Left)})./.({Int(b.Right)}))"
                        : $"BAS_IDIV({Int(b.Left)}, {Int(b.Right)})",
                    "MOD" => IsNonZeroConst(b.Right)
                        ? $"(({Int(b.Left)}).MOD.({Int(b.Right)}))"
                        : $"BAS_IMOD({Int(b.Left)}, {Int(b.Right)})",
                    "AND" => $"(({Int(b.Left)}) AND ({Int(b.Right)}))",
                    "OR" => $"(({Int(b.Left)}) OR ({Int(b.Right)}))",
                    "XOR" => $"(({Int(b.Left)}) XOR ({Int(b.Right)}))",
                    _ => throw new InvalidOperationException(b.Op),
                };
            case HuCall c:
                return c.Name switch
                {
                    "INP" => $"PORT[{Int(c.Args[0])}]",
                    "ASC" => $"BAS_SASC({Str(c.Args[0])})",
                    "VAL" => $"BAS_SVAL({Str(c.Args[0])})",
                    "STICK" => $"BAS_STICK({Int(c.Args[0])})",
                    "STRIG" => $"BAS_STRIG({Int(c.Args[0])})",
                    FlatPseudo.ReadNum => "BAS_READN()",
                    _ => throw new InvalidOperationException(c.Name),
                };
        }
        throw new InvalidOperationException(e.ToString());
    }

    private static bool IsNonZeroConst(HuExpr e) => HuAnalyzer.ConstValue(e) is long v && (v & 0xFFFF) != 0;

    // ------------------------------------------------------------ 浮動小数

    public static string FTempName(int i) => "H_F" + i;

    private string NewFTemp()
    {
        _ftemp++;
        _maxFtemp = Math.Max(_maxFtemp, _ftemp);
        return FTempName(_ftemp);
    }

    private int FConstId(double v)
    {
        var key = BitConverter.DoubleToInt64Bits(v == 0 ? 0.0 : v);
        if (!_fconstIds.TryGetValue(key, out var id))
        {
            id = _fconsts.Count;
            _fconsts.Add(v);
            _fconstIds[key] = id;
        }
        return id;
    }

    /// <summary>浮動小数の定数の値 (表の要素)</summary>
    private string FConst(double v) => $"H_FK[{FConstId(v)}]";

    /// <summary>浮動小数の定数の番地 (1 要素 3 バイト)</summary>
    private string FConstAddr(double v) => $"(H_FK+{FConstId(v) * 3})";

    /// <summary>SLANG の FLOAT の定数の綴り (SLANG の字句は指数の書き方を読めないので、指数を使わずに書く)</summary>
    public static string FloatLiteral(double v)
        => v.ToString("0.0" + new string('#', 40), System.Globalization.CultureInfo.InvariantCulture);

    /// <summary>浮動小数の式 (SLANG の FLOAT の式)。整数の式は一時変数に入れて浮動小数にする</summary>
    private string Flt(HuExpr e)
    {
        switch (e)
        {
            case HuFloat f:
                return FConst(f.Value);
            case HuNum n:
                return FConst(HuF24.SignedInt(n.Value));
            case HuUnary { Op: "+" } u:
                return Flt(u.Operand);
            case HuUnary { Op: "-" } u:
                return $"({FConst(0)}-{Flt(u.Operand)})";
            case HuBinary b when b.Type == HuType.Float:
                return b.Op switch
                {
                    "+" or "-" or "*" => $"({Flt(b.Left)}{b.Op}{Flt(b.Right)})",
                    "/" => $"BAS_FDIV({FAddr(b.Left)}, {FAddr(b.Right)})",
                    _ => throw new InvalidOperationException(b.Op),
                };
            case HuCall { Name: "RND" }:
                return "FRAND()";
            case HuCall { Name: "INT" } c:
                return $"BAS_FFLOOR({Flt(c.Args[0])})";
        }
        // 整数の式: 浮動小数の一時変数に入れる (SLANG が i16tof24 で変換する)
        var t = NewFTemp();
        _pre.Add($"{t}={Int(e)};");
        return t;
    }

    /// <summary>浮動小数の値の番地 (定数は表の要素、それ以外は一時変数に入れて、その番地)</summary>
    private string FAddr(HuExpr e)
    {
        if (e is HuFloat f) return FConstAddr(f.Value);
        if (e is HuNum n) return FConstAddr(HuF24.SignedInt(n.Value));
        var v = Flt(e);
        if (System.Text.RegularExpressions.Regex.IsMatch(v, @"^H_F\d+$")) return "&" + v;
        var t = NewFTemp();
        _pre.Add($"{t}={v};");
        return "&" + t;
    }

    /// <summary>浮動小数の定数と、それに符号を付けただけの式の値 (それ以外は null)</summary>
    private static double? ConstFloat(HuExpr e) => e switch
    {
        HuFloat f => f.Value,
        HuUnary { Op: "-" } u => ConstFloat(u.Operand) is double v ? -v : null,
        HuUnary { Op: "+" } u => ConstFloat(u.Operand),
        _ => null,
    };

    /// <summary>
    /// 浮動小数を整数にする (四捨五入。絶対値 65535 までは 16 ビットに回り込み、それを超えるとエラー 6)。
    /// 定数は変換のときに計算する。INT(整数の式) は何もしない。
    /// </summary>
    private string IntFromFloat(HuExpr e)
    {
        if (ConstFloat(e) is double cv)
        {
            // 実行時と同じ値にするため、SLANG が定数を f24 に直したときの値を丸める (.499999 は f24 では .5)
            var r = Math.Round(HuF24.Quantize(cv), MidpointRounding.AwayFromZero);
            if (Math.Abs(r) <= 65535) return Num(unchecked((short)(int)r));
        }
        if (e is HuCall { Name: "INT" } c && c.Args[0].Type == HuType.Int)
            return Int(c.Args[0]);
        return $"BAS_FTOIR({Flt(e)})";
    }

    /// <summary>文字列の式 (長さ付きバッファへのポインタ)</summary>
    private string Str(HuExpr e)
    {
        switch (e)
        {
            case HuStr s:
                return LiteralName(_prog.LiteralId(s.Text));
            case HuVar v:
                return StrVarName(v.Name);
            case HuBinary { Op: "+" } b:
                return $"BAS_SCAT({Str(b.Left)}, {Str(b.Right)})";
            case HuCall c:
                return c.Name switch
                {
                    "MID$" => $"BAS_SMID({Str(c.Args[0])}, {Int(c.Args[1])}, {(c.Args.Count > 2 ? Int(c.Args[2]) : "255")})",
                    "RIGHT$" => $"BAS_SRIGHT({Str(c.Args[0])}, {Int(c.Args[1])})",
                    "CHR$" => $"BAS_SCHR({Int(c.Args[0])})",
                    "HEXCHR$" => $"BAS_SHEX({Str(c.Args[0])})",
                    "CGPAT$" => $"BAS_SCGPAT({Int(c.Args[0])})",
                    "INKEY$" => "BAS_SINKEY()",
                    FlatPseudo.ReadStr => "BAS_READS()",
                    _ => throw new InvalidOperationException(c.Name),
                };
        }
        throw new InvalidOperationException(e.ToString());
    }
}
