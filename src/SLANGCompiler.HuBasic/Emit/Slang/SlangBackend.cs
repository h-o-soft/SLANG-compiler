using System.Text;
using SLANGCompiler.HuBasic.Analysis;
using SLANGCompiler.HuBasic.Lowering;
using SLANGCompiler.HuBasic.Parsing;

namespace SLANGCompiler.HuBasic.Emit.Slang;

/// <summary>
/// SLANG のソースを出す後段。
/// 名前 (変数の鍵ごと): 整数変数 V_名前、単精度 F_名前、倍精度 D_名前、文字列変数 S_名前、整数配列 A_名前、
/// 浮動小数の配列 FA_名前・DA_名前、文字列の配列 SA_名前 (1 要素 256 バイト)、隠し変数 H_…、文字列リテラル K_番号、行ラベル L行番号。
/// 浮動小数の定数の表 H_FK[]、浮動小数の一時変数 H_F番号。
/// 全体を MAIN() 1 関数にし、すべての二項演算を括弧で囲んで優先順位を固定する。
/// 浮動小数: SLANG は小数部のない FLOAT の定数どうしを整数として畳み込むので、定数はすべて表 H_FK[] から読む。
/// 割り算・比較・整数からの変換は、値を一時変数に入れてから (その文の行の前に代入を出して) 番地で渡す。
/// </summary>
public sealed class SlangBackend : IHuBackend
{
    /// <summary>
    /// 出力とランタイム (libx1_basic.asm の BAS_ABI_n) の組の印の番号。出力は MAIN の最初に BAS_ABI_n() を呼ぶ。
    /// 出力とランタイムの約束を変えたら、ランタイムの印と一緒に 1 つ上げる
    /// </summary>
    public const int BasAbi = 1;

    private readonly StringBuilder _sb = new();   // MAIN の本体
    private HuProgram _prog = null!;
    private readonly List<string> _pre = new();   // いまの文の行の前に出す代入 (浮動小数の一時変数)
    private readonly List<double> _fconsts = new();
    private readonly Dictionary<long, int> _fconstIds = new();
    private int _ftemp;      // いまの文で使った浮動小数の一時変数の数
    private int _maxFtemp;   // 文ごとの最大 (宣言する数)
    private int _itemp;      // いまの文で使った整数 (と文字列のポインタ) の一時変数の数
    private int _maxItemp;

    /// <summary>浮動小数の定数の表と一時変数 (1 つ 3 バイト)、整数の一時変数 (1 つ 2 バイト) の大きさ</summary>
    public int ExtraStaticBytes => (_fconsts.Count + _maxFtemp) * 3 + _maxItemp * 2;

    public string Emit(HuProgram program, HuFlat flat, HuEmitOptions options)
    {
        _prog = program;
        _sb.Clear();
        _pre.Clear();
        _fconsts.Clear();
        _fconstIds.Clear();
        _maxFtemp = 0;
        _maxItemp = 0;
        // 本体を先に作る (浮動小数の定数と一時変数の数は、本体を作り終えるまで分からない)
        foreach (var op in flat.Ops) EmitOp(op, options);

        var head = new StringBuilder();
        head.AppendLine("// generated by hubasic2sl - do not edit");
        if (options.SourceName.Length > 0) head.AppendLine($"// source: {options.SourceName}");
        if (options.DiskMainName.Length > 0) head.AppendLine($"// disk-main-name: {options.DiskMainName}");
        head.AppendLine();
        EmitDeclarations(head, flat);
        head.AppendLine();
        head.AppendLine("MAIN()");
        head.AppendLine("BEGIN");
        head.AppendLine($"  BAS_ABI_{BasAbi}();");
        head.Append(_sb);
        head.AppendLine("END;");
        return head.ToString();
    }

    // ------------------------------------------------------------ 名前

    /// <summary>単純変数の名前 (key は変数の鍵: 接尾辞付きの名前)</summary>
    public static string VarName(string key) => HuProgram.KindOfKey(key) switch
    {
        HuVarKind.Int => "V_",
        HuVarKind.Single => "F_",
        HuVarKind.Double => "D_",
        _ => "S_",
    } + key[..^1];

    /// <summary>配列の名前 (整数の配列はいままでどおり A_名前)</summary>
    public static string ArrayName(string key) => ArrayPrefix(key) + key[..^1];

    private static string ArrayPrefix(string key) => HuProgram.KindOfKey(key) switch
    {
        HuVarKind.Int => "A_",
        HuVarKind.Single => "FA_",
        HuVarKind.Double => "DA_",
        _ => "SA_",
    };

    public static string LiteralName(int id) => "K_" + id;

    /// <summary>配列の隠し変数の名前の後ろ (整数の配列は名前だけ、浮動小数は F_・D_、文字列は S_ を付けて見分ける)</summary>
    private static string ArrayTag(string key) => HuProgram.KindOfKey(key) switch
    {
        HuVarKind.Int => key[..^1],
        HuVarKind.Single => "F_" + key[..^1],
        HuVarKind.Double => "D_" + key[..^1],
        _ => "S_" + key[..^1],
    };

    public static string HiddenName(string hidden)
    {
        if (hidden == HuLowerer.Temp) return "H_T";
        if (hidden == HuLowerer.CurrentLine) return "H_LINE";
        if (hidden == HuLowerer.PokeAddr) return "H_PK";
        if (hidden.StartsWith("DIM:")) return "H_DIM_" + ArrayTag(hidden[4..]);
        if (hidden.StartsWith("UB:")) return "H_UB_" + ArrayTag(hidden[3..]);
        if (hidden.StartsWith("UB2:")) return "H_UB2_" + ArrayTag(hidden[4..]);
        return "H_" + hidden;
    }

    /// <summary>構文木の変数 (ソースの綴り) の SLANG の名前</summary>
    private string Var(HuVar v) => VarName(_prog.Key(v.Name));

    // ------------------------------------------------------------ 宣言

    private void EmitDeclarations(StringBuilder _sb, HuFlat flat)
    {
        var vars = _prog.IntVars.Select(VarName).Concat(flat.HiddenVars.Select(HiddenName)).ToList();
        foreach (var chunk in vars.Chunk(8))
            _sb.AppendLine($"VAR {string.Join(", ", chunk)};");
        // 浮動小数の変数 (SLANG は変数ごとに型を書かないと WORD になる)
        foreach (var chunk in _prog.FloatVars.Select(k => "FLOAT " + VarName(k)).Chunk(8))
            _sb.AppendLine($"VAR {string.Join(", ", chunk)};");
        // 浮動小数の一時変数 (SLANG は変数ごとに型を書かないと WORD になる)
        foreach (var chunk in Enumerable.Range(1, _maxItemp).Select(ITempName).Chunk(8))
            _sb.AppendLine($"VAR {string.Join(", ", chunk)};");
        var ftemps = Enumerable.Range(1, _maxFtemp).Select(i => "FLOAT " + FTempName(i)).ToList();
        foreach (var chunk in ftemps.Chunk(8))
            _sb.AppendLine($"VAR {string.Join(", ", chunk)};");
        if (_fconsts.Count > 0)
            _sb.AppendLine($"ARRAY FLOAT H_FK[] = {{ {string.Join(", ", _fconsts.Select(FloatLiteral))} }};");
        foreach (var (key, bound) in _prog.Arrays)
            _sb.AppendLine(HuProgram.KindOfKey(key) switch
            {
                HuVarKind.Int => $"ARRAY {ArrayName(key)}[{bound}];",
                // 文字列の配列: 文字列の変数と同じ 長さの上限 + 1 バイトのバッファを上限 + 1 個並べる
                HuVarKind.Str => $"ARRAY BYTE {ArrayName(key)}[{(bound + 1) * (_prog.StringLen + 1) - 1}];",
                _ => $"ARRAY FLOAT {ArrayName(key)}[{bound}];",
            });
        foreach (var s in _prog.StrVars)
            _sb.AppendLine($"ARRAY BYTE {VarName(s)}[{_prog.StringLen}];");
        for (int i = 0; i < _prog.Literals.Count; i++)
        {
            var text = _prog.Literals[i];
            var bytes = new List<int> { text.Length };
            bytes.AddRange(text.Select(c => (int)c));
            _sb.AppendLine($"ARRAY BYTE {LiteralName(i)}[] = {{ {string.Join(",", bytes)} }};");
        }
        if (_prog.DataBytes.Length > 0)
        {
            _sb.AppendLine("ARRAY BYTE H_DATA[] = {");
            foreach (var chunk in _prog.DataBytes.Chunk(24))
                _sb.AppendLine("  " + string.Join(",", chunk.Select(b => b.ToString())) + ",");
            _sb.AppendLine("  0 };");
            var dl = new List<int>();
            foreach (var (line, offset) in _prog.DataLines)
            {
                dl.Add(line);
                dl.Add(offset);
            }
            dl.Add(0xFFFF);
            dl.Add(_prog.DataBytes.Length);
            // 初期値の並び (CODE リスト) の要素は既定で 1 バイト。2 バイトの要素は % を付ける
            _sb.AppendLine($"ARRAY H_DLINE[] = {{ {string.Join(",", dl.Select(v => "%" + Hex(v)))} }};");
        }
    }

    private static string Hex(int v) => v > 32767 || v < 0 ? $"${v & 0xFFFF:X4}" : v.ToString();

    // ------------------------------------------------------------ 文

    /// <summary>文の行を出す。その前に、式を作るときに溜まった一時変数への代入を出す</summary>
    private void Line(string s)
    {
        foreach (var p in _pre) _sb.Append("  ").AppendLine(p);
        _pre.Clear();
        _sb.Append("  ").AppendLine(s);
    }

    private void EmitOp(FlatOp op, HuEmitOptions options)
    {
        _ftemp = 0;
        _itemp = 0;
        switch (op)
        {
            case FLabel l:
                _sb.AppendLine($"{l.Name}:");
                break;
            case FLineMark m:
                if (options.LineComments) _sb.AppendLine($"  // BAS {m.Line}: {CommentSafe(m.Source)}");
                break;
            case FGoto g:
                Line($"GOTO {g.Label};");
                break;
            case FIf f:
                Line($"IF {Cond(f.Cond)}{(f.JumpIfTrue ? "" : "==0")} THEN GOTO {f.Label};");
                break;
            case FIfHidden fh:
            {
                var opText = fh.Op switch { "==" => "==", "<" => ".<.", ">" => ".>.", ">=" => ".>=.", _ => fh.Op };
                Line($"IF {HiddenName(fh.Hidden)} {opText} {Num(fh.Value)} THEN GOTO {fh.Label};");
                break;
            }
            case FAssign a:
                Assign(a.Target, a.Value);
                break;
            case FAssignHidden ah:
                Line($"{HiddenName(ah.Hidden)}={Int(ah.Value)};");
                break;
            case FCall c:
            {
                var call = $"{c.Function}({string.Join(", ", Args(c.Args))})";
                Line(c.Result != null ? $"{HiddenName(c.Result)}={call};" : $"{call};");
                break;
            }
            case FDispatch d:
            {
                var cases = string.Join(" ", d.Cases.Select(cs => $"{Num(cs.Value)}: GOTO {cs.Label};"));
                Line($"CASE {HiddenName(d.Hidden)} OF {{ {cases} }};");
                break;
            }
            case FPortOut po:
            {
                if ((HasInPlaceMirror(po.Value) || HasInPlaceMirror(po.Port)) && HuAnalyzer.ConstValue(po.Port) == null)
                {
                    // 値かポートが変数を書き換える MIRROR$ を含むときは、本物と同じくポートの番号を先に読む
                    var port = Int(po.Port);
                    int mark = _pre.Count;
                    var value = Int(po.Value);
                    var t = NewITemp();
                    _pre.Insert(mark, $"{t}={port};");
                    Line($"PORT[{t}]={value};");
                    break;
                }
                var pv = Seq((po.Port, K.Int), (po.Value, K.Int));
                Line($"PORT[{pv[0]}]={pv[1]};");
                break;
            }
            case FPoke pk:
            {
                // 値は BAS_BYTE で 0〜255 を調べる (外ならエラー 5)
                var target = $"{(pk.Io ? "PORT" : "MEM")}[{HiddenName(HuLowerer.PokeAddr)}{(pk.Offset > 0 ? "+" + pk.Offset : "")}]";
                Line($"{target}=BAS_BYTE({Seq((pk.Value, K.Int))[0]});");
                break;
            }
            case FSwap sw:
            {
                // 添字の検査は A・B の順に一時変数へ入れる (評価とエラーの順を左から右に)
                var a = SwapAddress(sw.A);
                var b = SwapAddress(sw.B);
                // 大きさ: 整数 2、浮動小数 3、文字列 0 (ランタイムが長さの大きい方 + 1 バイトを入れ替える)
                var size = sw.A.Type switch { HuType.Str => 0, HuType.Float => 3, _ => 2 };
                Line($"BAS_SWAP({a}, {b}, {size});");
                break;
            }
        }
    }

    private static string CommentSafe(string s)
    {
        var sb = new StringBuilder();
        foreach (var c in s) sb.Append(c >= 0x20 && c < 0x7F ? c : '?');
        return sb.ToString();
    }

    /// <summary>ランタイム呼び出しの引数を左から順に (式の評価の順を保つ。<see cref="Seq"/>)</summary>
    private IEnumerable<string> Args(IReadOnlyList<FArg> args)
    {
        var items = new List<(HuExpr E, K K)>();
        var index = new List<int>();
        for (int i = 0; i < args.Count; i++)
        {
            if (args[i] is FExprArg e) { index.Add(items.Count); items.Add((e.Expr, e.Expr.Type == HuType.Str ? K.Str : K.Int)); }
            else if (args[i] is FFloatArg f) { index.Add(items.Count); items.Add((f.Expr, K.Flt)); }
            else index.Add(-1);
        }
        var vals = Seq(items.ToArray());
        for (int i = 0; i < args.Count; i++)
            yield return index[i] >= 0 ? vals[index[i]] : Arg(args[i]);
    }

    private string Arg(FArg a) => a switch
    {
        FExprArg e => e.Expr.Type == HuType.Str ? Str(e.Expr) : Int(e.Expr),
        FFloatArg f => Flt(f.Expr),
        FIntArg i => Num(i.Value),
        FAddrArg av => "&" + LValueName(av.Var),
        FFloatAddrArg fa => FAddr(fa.Expr),
        FHiddenAddrArg h => "&" + HiddenName(h.Hidden),
        FDataTableArg t => t.LineTable ? "H_DLINE" : "H_DATA",
        _ => throw new InvalidOperationException(a.ToString()),
    };

    private static string Num(int v) => v < 0 ? $"(0-{-v})" : Hex(v);

    private string LValueName(HuExpr e) => e switch
    {
        HuVar v => Var(v),
        _ => throw new InvalidOperationException("address of " + e),
    };

    private string LValue(HuExpr e) => e switch
    {
        HuVar v => Var(v),
        HuIndex ix => ArrayElement(ix),
        _ => throw new InvalidOperationException(e.ToString()),
    };

    /// <summary>SWAP の相手の番地 (文字列の変数は 256 バイトのバッファの名前がそのまま番地)</summary>
    private string SwapAddress(HuExpr e)
    {
        switch (e)
        {
            case HuVar v:
                return v.Type == HuType.Str ? Var(v) : "&" + Var(v);
            case HuIndex ix:
            {
                var t = NewITemp();
                _pre.Add($"{t}={ArrayIndex(ix)};");
                return ix.Type == HuType.Str ? StrElement(ix, t) : $"&{ArrayName(_prog.Key(ix.Name))}[{t}]";
            }
            default:
                throw new InvalidOperationException("SWAP " + e);
        }
    }

    private string ArrayElement(HuIndex ix) => $"{ArrayName(_prog.Key(ix.Name))}[{ArrayIndex(ix)}]";

    /// <summary>文字列の配列の要素のバッファの番地 (index は添字の式。1 要素 256 バイト)</summary>
    private string StrElement(HuIndex ix, string index)
    {
        // 1 要素は 長さの上限 + 1 バイト (既定 256 は <<8)。2 の累乗ならシフト、そうでなければ掛け算
        int size = _prog.StringLen + 1;
        var offset = (size & (size - 1)) == 0 ? $"{index}<<{System.Numerics.BitOperations.Log2((uint)size)}" : $"{index}*{size}";
        return $"({ArrayName(_prog.Key(ix.Name))}+({offset}))";
    }

    /// <summary>
    /// 配列の添字 (BAS_AIDX が範囲を調べて、初めて使う配列なら DIM なしの上限 10 で確保したことにする)。
    /// 2 次元は次元ごとに調べて「1 つめ × 置き場の 2 つめの大きさ + 2 つめ」に並べる。添字は左から決めるので、2 つめの式が前置きの代入を
    /// 出すか、その場で書き換える MIRROR$ を含むときは、1 つめをその前置きより前に一時変数へ入れる
    /// </summary>
    private string ArrayIndex(HuIndex ix)
    {
        var key = _prog.Key(ix.Name);
        var state = HiddenName(HuLowerer.DimState(key));
        var first = $"BAS_AIDX({Int(ix.Index)}, &{state}, &{HiddenName(HuLowerer.UpperBound(key))})";
        if (ix.Index2 == null) return first;
        int mark = _pre.Count;
        var second = Int(ix.Index2);
        if (_pre.Count > mark || HasInPlaceMirror(ix.Index2))
        {
            var t = NewITemp();
            _pre.Insert(mark, $"{t}={first};");
            first = t;
        }
        var stride = _prog.Arrays2[key].Bound2 + 1;
        return $"({first}*{Num(stride)}+BAS_AIDX({second}, &{state}, &{HiddenName(HuLowerer.UpperBound2(key))}))";
    }

    /// <summary>
    /// 数の変数・配列の要素への代入。HuBASIC は代入先の添字を先に調べる (A(9)=1/0 は Subscript out of range) が、
    /// SLANG は値を先に計算する。そこで代入先が配列の要素で、値の計算が前置きの代入 (一時変数) を出したとき、
    /// または浮動小数が関わる代入で値が定数と単純変数でないときは、添字の検査を値より先に一時変数へ入れる
    /// (整数だけの代入は、生成するコードを変えないためにいままでどおり。既知の違い)。INPUT の項目の代入は、1 行を読んだ
    /// 後なので、項目を取り出すのと添字を調べるのとどちらが先でも見え方は同じ (いままでどおり)
    /// </summary>
    private void Assign(HuExpr target, HuExpr value)
    {
        // 添字の式は 1 回だけ作る (作るときに出た前置きの代入は、この時点より前に並んでいる)
        var index = target is HuIndex ix ? ArrayIndex(ix) : null;
        var lv = index != null ? $"{ArrayName(_prog.Key(((HuIndex)target).Name))}[{index}]" : LValue(target);
        int mark = _pre.Count;
        var v = target.Type == HuType.Float ? Flt(value) : Int(value);
        // 整数に入れる浮動小数の単純変数も、整数にするとき (BAS_FTOIR) にエラー 6 になりうる (R2-F1)
        bool mayFail = NeedsOrder(value, target.Type == HuType.Float ? K.Flt : K.Int)
                       || (target.Type != HuType.Float && value is HuVar { Type: HuType.Float });
        bool floatOrder = (target.Type == HuType.Float || HasFloat(value)) && mayFail
                          && value is not HuCall { Name: FlatPseudo.InputNum };
        // 値か添字が変数を書き換える MIRROR$ を含むときも、本物と同じく添字を先に読む (N%(ASC(S$))=ASC(MIRROR$(S$)) は N%(1) に入れる)
        bool mirrorOrder = target is HuIndex mx && (HasInPlaceMirror(value) || HasInPlaceMirror(mx.Index));
        if ((_pre.Count > mark || floatOrder || mirrorOrder) && index != null)
        {
            var t = NewITemp();
            _pre.Insert(mark, $"{t}={index};");
            lv = $"{ArrayName(_prog.Key(((HuIndex)target).Name))}[{t}]";
        }
        Line($"{lv}={v};");
    }

    // ------------------------------------------------------------ 式

    private static readonly Dictionary<string, string> SignedCompare = new()
    {
        ["="] = "==", ["<>"] = "<>", ["<"] = ".<.", [">"] = ".>.", ["<="] = ".<=.", [">="] = ".>=.",
    };

    /// <summary>条件の位置の式。最上位が比較なら 1/0 のまま、それ以外は値そのもの (0 以外が真)。</summary>
    private string Cond(HuExpr e)
    {
        if (e is HuBinary b && SignedCompare.ContainsKey(b.Op))
            return Compare(b);
        // 浮動小数の条件は、四捨五入で整数にしてから 0 でないかを見る (HuBASIC の実測: IF .25 は偽、IF .5 は真)
        return $"({Int(e)})";
    }

    /// <summary>比較を SLANG の 1/0 の式にする</summary>
    private string Compare(HuBinary b)
    {
        if (b.Left.Type == HuType.Float || b.Right.Type == HuType.Float)
        {
            // 浮動小数の比較は BAS_FCMP (厳密に比べて -1/0/1) と 0 の比較にする
            var cmp = $"BAS_FCMP({FAddr(b.Left)}, {FAddr(b.Right)})";
            return $"({cmp} {SignedCompare[b.Op]} 0)";
        }
        if (b.Left.Type == HuType.Str)
        {
            var sv = Seq((b.Left, K.Str), (b.Right, K.Str));
            var cmp = $"BAS_SCMP({sv[0]}, {sv[1]})";
            return b.Op switch
            {
                "=" => $"({cmp}==0)",
                "<>" => $"({cmp}<>0)",
                _ => $"({cmp} {SignedCompare[b.Op]} 0)",
            };
        }
        var iv = Seq((b.Left, K.Int), (b.Right, K.Int));
        return $"(({iv[0]}) {SignedCompare[b.Op]} ({iv[1]}))";
    }

    /// <summary>整数の式 (値。比較は -1/0 に変換する)</summary>
    private string Int(HuExpr e)
    {
        if (e.Type == HuType.Float) return IntFromFloat(e);
        switch (e)
        {
            case HuNum n:
                return Num(n.Value);
            case HuVar v:
                return Var(v);
            case HuIndex ix:
                return ArrayElement(ix);
            case HuUnary u:
                return u.Op switch
                {
                    "-" => $"(0-({Int(u.Operand)}))",
                    "+" => Int(u.Operand),
                    _ => $"(CPL ({Int(u.Operand)}))", // NOT はビット反転
                };
            case HuBinary b:
                if (SignedCompare.ContainsKey(b.Op))
                    return $"(0-{Compare(b)})";
                var lr = Seq((b.Left, K.Int), (b.Right, K.Int));
                var (l, r) = (lr[0], lr[1]);
                return b.Op switch
                {
                    "+" => $"(({l})+({r}))",
                    "-" => $"(({l})-({r}))",
                    "*" => $"(({l})*({r}))",
                    "/" => $"BAS_IDIVR({l}, {r})",
                    "\\" => IsNonZeroConst(b.Right) ? $"(({l})./.({r}))" : $"BAS_IDIV({l}, {r})",
                    "MOD" => IsNonZeroConst(b.Right) ? $"(({l}).MOD.({r}))" : $"BAS_IMOD({l}, {r})",
                    "AND" => $"(({l}) AND ({r}))",
                    "OR" => $"(({l}) OR ({r}))",
                    "XOR" => $"(({l}) XOR ({r}))",
                    _ => throw new InvalidOperationException(b.Op),
                };
            case HuCall c:
                return c.Name switch
                {
                    "INP" or "PEEK@" => $"PORT[{Int(c.Args[0])}]",
                    "PEEK" => $"MEM[{Int(c.Args[0])}]",
                    "ASC" => $"BAS_SASC({Str(c.Args[0])})",
                    "STICK" => $"BAS_STICK({Int(c.Args[0])})",
                    "STRIG" => $"BAS_STRIG({Int(c.Args[0])})",
                    // ABS・FIX は引数が Int のとき (Float の引数なら式が Float になり、上で丸める)
                    "ABS" => $"BAS_IABS({Int(c.Args[0])})",
                    "FIX" => Int(c.Args[0]),
                    "SGN" => c.Args[0].Type == HuType.Float ? $"BAS_FSGN({Flt(c.Args[0])})" : $"BAS_ISGN({Int(c.Args[0])})",
                    "CINT" => Int(c.Args[0]),
                    "LEN" => $"BAS_SLEN({Str(c.Args[0])})",
                    "INSTR" => c.Args.Count > 2
                        ? Call("BAS_SINSTR", (c.Args[0], K.Int), (c.Args[1], K.Str), (c.Args[2], K.Str))
                        : $"BAS_SINSTR(1, {string.Join(", ", Seq((c.Args[0], K.Str), (c.Args[1], K.Str)))})",
                    _ => throw new InvalidOperationException(c.Name),
                };
        }
        throw new InvalidOperationException(e.ToString());
    }

    /// <summary>式のどこかに浮動小数の値があるか</summary>
    private static bool HasFloat(HuExpr e) => e.Type == HuType.Float || e switch
    {
        HuIndex ix => HasFloat(ix.Index) || (ix.Index2 != null && HasFloat(ix.Index2)),
        HuUnary u => HasFloat(u.Operand),
        HuBinary b => HasFloat(b.Left) || HasFloat(b.Right),
        HuCall c => c.Args.Any(HasFloat),
        _ => false,
    };

    /// <summary>変数・配列の要素をその場で書き換える MIRROR$ か</summary>
    private static bool IsInPlaceMirror(HuCall c) => c is { Name: "MIRROR$", Args: [HuVar or HuIndex] };

    /// <summary>変数・配列の要素をその場で書き換える MIRROR$ を (入れ子の中も) 含むか</summary>
    private static bool HasInPlaceMirror(HuExpr e) => e switch
    {
        HuCall c => IsInPlaceMirror(c) || c.Args.Any(HasInPlaceMirror),
        HuIndex ix => HasInPlaceMirror(ix.Index) || (ix.Index2 != null && HasInPlaceMirror(ix.Index2)),
        HuUnary u => HasInPlaceMirror(u.Operand),
        HuBinary b => HasInPlaceMirror(b.Left) || HasInPlaceMirror(b.Right),
        _ => false,
    };

    private static bool IsNonZeroConst(HuExpr e) => HuAnalyzer.ConstValue(e) is long v && (v & 0xFFFF) != 0;

    // ------------------------------------------------------------ 浮動小数

    public static string FTempName(int i) => "H_F" + i;

    private string NewFTemp()
    {
        _ftemp++;
        _maxFtemp = Math.Max(_maxFtemp, _ftemp);
        return FTempName(_ftemp);
    }

    private int FConstId(double v)
    {
        var key = BitConverter.DoubleToInt64Bits(v == 0 ? 0.0 : v);
        if (!_fconstIds.TryGetValue(key, out var id))
        {
            id = _fconsts.Count;
            _fconsts.Add(v);
            _fconstIds[key] = id;
        }
        return id;
    }

    /// <summary>浮動小数の定数の値 (表の要素)</summary>
    private string FConst(double v) => $"H_FK[{FConstId(v)}]";

    /// <summary>浮動小数の定数の番地 (1 要素 3 バイト)</summary>
    private string FConstAddr(double v) => $"(H_FK+{FConstId(v) * 3})";

    /// <summary>
    /// SLANG の FLOAT の定数の綴り。先に f24 の値にしてから、その値を正確に表す 10 進で書く (桁を落とすと、SLANG が
    /// f24 に直したときに別の値になることがある)。f24 の値は「整数 × 2 の累乗」なので、有限の桁で正確に書ける。
    /// SLANG の字句は指数の書き方を読めないので、指数は使わない。
    /// </summary>
    public static string FloatLiteral(double v)
    {
        var q = HuF24.Quantize(v);
        if (q == 0) return "0.0";
        var neg = q < 0;
        long bits = BitConverter.DoubleToInt64Bits(Math.Abs(q));
        int exp = (int)((bits >> 52) & 0x7FF);
        long mant = bits & 0xFFFFFFFFFFFFFL;
        if (exp != 0) mant |= 1L << 52; else exp = 1;
        exp -= 1075;                                  // |q| = mant × 2^exp
        string text;
        if (exp >= 0)
            text = (new System.Numerics.BigInteger(mant) << exp).ToString() + ".0";
        else
        {
            // mant × 2^exp = mant × 5^(-exp) / 10^(-exp)
            var digits = (mant * System.Numerics.BigInteger.Pow(5, -exp)).ToString().PadLeft(-exp + 1, '0');
            var intPart = digits[..^(-exp)];
            var frac = digits[^(-exp)..].TrimEnd('0');
            text = intPart + "." + (frac.Length > 0 ? frac : "0");
        }
        return neg ? "-" + text : text;
    }

    /// <summary>浮動小数の式 (SLANG の FLOAT の式)。整数の式は一時変数に入れて浮動小数にする</summary>
    private string Flt(HuExpr e)
    {
        switch (e)
        {
            case HuFloat f:
                return FConst(f.Value);
            case HuNum n:
                return FConst(HuF24.SignedInt(n.Value));
            case HuVar v when v.Type == HuType.Float:
                return Var(v);
            case HuIndex ix when ix.Type == HuType.Float:
                return ArrayElement(ix);
            // 符号は、浮動小数の式のときだけ浮動小数で計算する (整数の -X は整数で計算してから変換する。
            // X が -32768 のとき、先に浮動小数にすると 32768 になって値が変わるため)
            case HuUnary { Op: "+" } u when u.Type == HuType.Float:
                return Flt(u.Operand);
            case HuUnary { Op: "-" } u when u.Type == HuType.Float:
                return $"({FConst(0)}-{Flt(u.Operand)})";
            case HuBinary b when b.Type == HuType.Float:
                return b.Op switch
                {
                    "+" or "-" or "*" => FltPair(b),
                    "/" => $"BAS_FDIV({FAddr(b.Left)}, {FAddr(b.Right)})",
                    "^" => $"BAS_FPOW({FAddr(b.Left)}, {FAddr(b.Right)})",
                    _ => throw new InvalidOperationException(b.Op),
                };
            case HuCall { Name: "RND" }:
                return "FRAND()";
            case HuCall { Name: "TIME" }:
            {
                // TIME ÷ 4 と TIME mod 4 を続けて読む (どちらも 32767 以下なので、符号付きの整数 → FLOAT の変換で正しい)。
                // 2 つの代入を一度に前置きに足すので、間に別の TIME の BAS_TIMEH が入らない
                var hi = NewFTemp();
                var lo = NewFTemp();
                _pre.Add($"{hi}=BAS_TIMEH();");
                _pre.Add($"{lo}=BAS_TIMEL();");
                return $"({hi}*{FConst(4)}+{lo})";
            }
            case HuCall { Name: FlatPseudo.InputNum }:
                return "BAS_INFN()";
            case HuCall { Name: FlatPseudo.ReadNum }:
                return "BAS_READF()";
            case HuCall { Name: "VAL" } c:
                return $"BAS_SVALF({Str(c.Args[0])})";
            case HuCall { Name: "INT" } c:
                return $"BAS_FFLOOR({Flt(c.Args[0])})";
            case HuCall { Name: "CSNG" or "CDBL" } c:
                return Flt(c.Args[0]);
            case HuCall { Name: "PAI" } c:
                return $"({Flt(c.Args[0])}*{FConst(Math.PI)})";
            case HuCall { Name: "RAD" } c:
                return $"({Flt(c.Args[0])}*{FConst(Math.PI / 180)})";
            case HuCall c when c.Type == HuType.Float && FloatFunctions.TryGetValue(c.Name, out var fn):
                return $"{fn}({Flt(c.Args[0])})";
        }
        // 整数の式: 浮動小数の一時変数に入れる (SLANG が i16tof24 で変換する)
        var t = NewFTemp();
        _pre.Add($"{t}={Int(e)};");
        return t;
    }

    /// <summary>浮動小数を 1 つ受けて浮動小数を返す関数と、ランタイムの名前 (ABS・FIX は引数が Float のとき)</summary>
    private static readonly Dictionary<string, string> FloatFunctions = new()
    {
        ["ABS"] = "FABS", ["FIX"] = "BAS_FFIX", ["FRAC"] = "BAS_FFRAC", ["SQR"] = "BAS_FSQR", ["LOG"] = "BAS_FLOG",
        ["EXP"] = "FEXP", ["SIN"] = "FSIN", ["COS"] = "FCOS", ["TAN"] = "FTAN", ["ATN"] = "FATAN",
    };

    private string FltPair(HuBinary b)
    {
        var v = Seq((b.Left, K.Flt), (b.Right, K.Flt));
        return $"({v[0]}{b.Op}{v[1]})";
    }

    // ------------------------------------------------------------ 評価の順

    private enum K { Int, Str, Flt }

    public static string ITempName(int i) => "H_I" + i;

    private string NewITemp()
    {
        _itemp++;
        _maxItemp = Math.Max(_maxItemp, _itemp);
        return ITempName(_itemp);
    }

    /// <summary>
    /// 評価の順を守る必要がある式か: 定数と単純変数の読み出し以外のすべて (関数・演算・配列の要素は、入力や乱数で
    /// 結果が変わったり、0 で割る・添字の範囲外などの実行時エラーになったりするので、後ろの式より先に評価する)。
    /// 整数にする位置の浮動小数の定数は、変換のときに整数にできるもの (丸めて 65535 以内) だけを除く
    /// (それ以外は実行時に BAS_FTOIR でエラー 6 になる)
    /// </summary>
    private static bool NeedsOrder(HuExpr e, K k) => e switch
    {
        HuNum or HuStr or HuVar => false,
        HuFloat f => k == K.Int && Math.Abs(Math.Round(HuF24.Quantize(f.Value), MidpointRounding.AwayFromZero)) > 65535,
        _ => true,
    };

    /// <summary>
    /// 式の並びを、左から順に評価される形で出す。後ろの式が前置きの代入 (一時変数) を出したときは、それより前にある
    /// 定数と単純変数以外の式を一時変数に入れて、その前置きの前に置く (前置きは文の行より前に実行されるため、
    /// そのままだと後ろの式の一部が先に評価され、入力の順や実行時エラーの順が変わる)。
    /// </summary>
    private string[] Seq(params (HuExpr E, K K)[] items)
    {
        var outs = new string[items.Length];
        var done = new bool[items.Length];
        for (int i = 0; i < items.Length; i++)
        {
            int mark = _pre.Count;
            outs[i] = items[i].K switch { K.Int => Int(items[i].E), K.Str => Str(items[i].E), _ => Flt(items[i].E) };
            if (_pre.Count == mark) continue;
            int at = mark;
            for (int j = 0; j < i; j++)
            {
                if (done[j] || !NeedsOrder(items[j].E, items[j].K)) continue;
                var t = items[j].K == K.Flt ? NewFTemp() : NewITemp();
                _pre.Insert(at++, $"{t}={outs[j]};");
                outs[j] = t;
                done[j] = true;
            }
        }
        return outs;
    }

    /// <summary>
    /// CHR$(a, b, …): 結果の長さの文字列を先に 1 つ確保して、1 文字ずつ書く (連結を重ねると途中の文字列が一時領域に
    /// 残ってあふれるため)。確保と書き込みは前置きの代入として出し、引数は左から順に評価する
    /// </summary>
    private string ChrOfCodes(HuCall c)
    {
        var t = NewITemp();
        _pre.Add($"{t}=BAS_SALLOC({c.Args.Count});");
        for (int i = 0; i < c.Args.Count; i++)
        {
            var v = Int(c.Args[i]);
            _pre.Add($"BAS_SPUTC({t}, {i + 1}, {v});");
        }
        return t;
    }

    /// <summary>STRING$(n, 文字コード): その文字を 1 文字にしてから繰り返す</summary>
    private string StringOfCode(HuCall c)
    {
        var v = Seq((c.Args[0], K.Int), (c.Args[1], K.Int));
        return $"BAS_SSTR({v[0]}, BAS_SCHR({v[1]}))";
    }

    /// <summary>関数の呼び出しを、引数を左から順に評価する形で出す</summary>
    private string Call(string function, params (HuExpr E, K K)[] args)
        => $"{function}({string.Join(", ", Seq(args))})";

    /// <summary>浮動小数の値の番地 (定数は表の要素、それ以外は一時変数に入れて、その番地)</summary>
    private string FAddr(HuExpr e)
    {
        if (e is HuFloat f) return FConstAddr(f.Value);
        if (e is HuNum n) return FConstAddr(HuF24.SignedInt(n.Value));
        // 浮動小数の単純変数はその番地 (式の評価の途中で変数の値は変わらない)
        if (e is HuVar fv && fv.Type == HuType.Float) return "&" + Var(fv);
        var v = Flt(e);
        if (System.Text.RegularExpressions.Regex.IsMatch(v, @"^H_F\d+$")) return "&" + v;
        var t = NewFTemp();
        _pre.Add($"{t}={v};");
        return "&" + t;
    }

    /// <summary>浮動小数の定数と、それに符号を付けただけの式の値 (それ以外は null)</summary>
    private static double? ConstFloat(HuExpr e) => e switch
    {
        HuFloat f => f.Value,
        HuUnary { Op: "-" } u => ConstFloat(u.Operand) is double v ? -v : null,
        HuUnary { Op: "+" } u => ConstFloat(u.Operand),
        _ => null,
    };

    /// <summary>
    /// 浮動小数を整数にする (四捨五入。絶対値 65535 までは 16 ビットに回り込み、それを超えるとエラー 6)。
    /// 定数は変換のときに計算する。INT(整数の式) は何もしない。
    /// </summary>
    private string IntFromFloat(HuExpr e)
    {
        if (ConstFloat(e) is double cv)
        {
            // 実行時と同じ値にするため、SLANG が定数を f24 に直したときの値を丸める (.499999 は f24 では .5)
            var r = Math.Round(HuF24.Quantize(cv), MidpointRounding.AwayFromZero);
            if (Math.Abs(r) <= 65535) return Num(unchecked((short)(int)r));
        }
        if (e is HuCall { Name: "INT" } c && c.Args[0].Type == HuType.Int)
            return Int(c.Args[0]);
        return $"BAS_FTOIR({Flt(e)})";
    }

    /// <summary>文字列の式 (長さ付きバッファへのポインタ)</summary>
    private string Str(HuExpr e)
    {
        switch (e)
        {
            case HuStr s:
                return LiteralName(_prog.LiteralId(s.Text));
            case HuVar v:
                return Var(v);
            case HuIndex ix:
                return StrElement(ix, ArrayIndex(ix));
            case HuBinary { Op: "+" } b:
            {
                var sv = Seq((b.Left, K.Str), (b.Right, K.Str));
                return $"BAS_SCAT({sv[0]}, {sv[1]})";
            }
            case HuCall c:
                return c.Name switch
                {
                    "MID$" => c.Args.Count > 2
                        ? Call("BAS_SMID", (c.Args[0], K.Str), (c.Args[1], K.Int), (c.Args[2], K.Int))
                        : $"BAS_SMID({string.Join(", ", Seq((c.Args[0], K.Str), (c.Args[1], K.Int)))}, 255)",
                    "LEFT$" => $"BAS_SMID({string.Join(", 1, ", Seq((c.Args[0], K.Str), (c.Args[1], K.Int)))})",
                    "STRING$" => c.Args[1].Type == HuType.Str
                        ? Call("BAS_SSTR", (c.Args[0], K.Int), (c.Args[1], K.Str))
                        : StringOfCode(c),
                    "CHARACTER$" => Call("BAS_SCHARA", (c.Args[0], K.Int), (c.Args[1], K.Int)),
                    "SCRN$" => Call("BAS_SSCRN", (c.Args[0], K.Int), (c.Args[1], K.Int), (c.Args[2], K.Int)),
                    "INKEY$" when c.Args.Count > 0 => "BAS_SINKEY0()",
                    "INPUT$" => $"BAS_SINPUT({Int(c.Args[0])})",
                    FlatPseudo.InputStr => "BAS_INFS()",
                    // CHR$(a, b, …) は 1 文字ずつ作って左からつなげる
                    "CHR$" when c.Args.Count > 1 => ChrOfCodes(c),
                    "RIGHT$" => Call("BAS_SRIGHT", (c.Args[0], K.Str), (c.Args[1], K.Int)),
                    "CHR$" => $"BAS_SCHR({Int(c.Args[0])})",
                    "HEXCHR$" => $"BAS_SHEX({Str(c.Args[0])})",
                    // 本物の MIRROR$ は、引数が変数・配列の要素ならその中身をその場で書き換え、結果もその中身になる
                    "MIRROR$" => IsInPlaceMirror(c)
                        ? $"BAS_SMIRRORV({Str(c.Args[0])})"
                        : $"BAS_SMIRROR({Str(c.Args[0])})",
                    "CGPAT$" => $"BAS_SCGPAT({Int(c.Args[0])})",
                    "HEX$" => $"BAS_SHEXS({Int(c.Args[0])})",
                    "BIN$" => $"BAS_SBINS({Int(c.Args[0])})",
                    // SPACE$(n) は STRING$(n," ") と同じ (n の範囲の検査も同じ)
                    "SPACE$" => $"BAS_SSTR({Int(c.Args[0])}, BAS_SCHR(32))",
                    // STR$ は整数も浮動小数にしてから PRINT の形で文字列にする (後ろの空白は付けない)
                    "STR$" => $"BAS_SFSTR({Flt(c.Args[0])})",
                    "INKEY$" => "BAS_SINKEY()",
                    FlatPseudo.ReadStr => "BAS_READS()",
                    _ => throw new InvalidOperationException(c.Name),
                };
        }
        throw new InvalidOperationException(e.ToString());
    }
